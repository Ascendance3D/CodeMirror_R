//! wrapping, then after the operation `doc.scrollLeft`, `doc.scrollTop`, and after
//! the later operations of the case `doc.scrollLeft`, `doc.scrollTop`, the selection,
//! the UTF-16 length and the undo and redo depth. The replacements are "short" (`a\nb`),
//! "ylong" (60 lines of 150 `y`), "empty" and "multi" (four lines); the starting
//! documents are 60 lines of 150 `x` (long), 60 lines of `ab` (short) or empty.

