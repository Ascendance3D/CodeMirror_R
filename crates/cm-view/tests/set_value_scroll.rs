/// Two editors: the reset is the replaced editor's alone (M01, M01b).
#[test]
fn editors_reset_on_their_own() {
    for name in ["short", "ylong"] {
        let (mut a, mut b) = (editor(Long, false), editor(Long, false));
        a.scroll_to(Some(300.0), Some(800.0));
        b.scroll_to(Some(200.0), Some(600.0));
        a.set_value(&text(name, Long));
        assert_eq!((a.display.scroll_left, a.display.scroll_top), (0.0, 0.0));
        assert_eq!(
            (b.display.scroll_left, b.display.scroll_top),
            (200.0, 600.0)
        );
    }
}

/// `setValue` on a linked document that has no editor does not move the editor
/// (M04L): the shared text changes, the editor keeps its scroll while it still fits.
#[test]
fn linked_document_without_editor() {
    let mut cm = editor(Long, false);
    let linked = cm
        .doc
        .linked_doc(LinkedDocOptions {
            shared_hist: true,
            ..Default::default()
        })
        .unwrap();
    cm.scroll_to(Some(300.0), Some(800.0));
    linked.set_value(&text("ylong", Long));
    assert!(linked.take_scroll_resets().is_empty());
    assert_eq!(cm.doc.take_scroll_resets(), Vec::<usize>::new());
    cm.run_op(|_| {});
    assert_eq!(
        (cm.display.scroll_left, cm.display.scroll_top),
        (300.0, 800.0)
    );
}
