fn doc_text(doc: Doc) -> String {
    match doc {
        Long => vec!["x".repeat(150); 60].join("\n"),
        Short => vec!["ab"; 60].join("\n"),
        Empty => String::new(),
    }
}

/// The replacement named in the recording; "same" is the starting document.
fn text(name: &str, doc: Doc) -> String {
    match name {
        "short" => "a\nb".into(),
        "empty" => String::new(),
        "long" => doc_text(Long),
        "ylong" => vec!["y".repeat(150); 60].join("\n"),
        "multi" => "one\ntwo\nthree\nfour".into(),
        "same" => doc_text(doc),
        _ => panic!("{name}"),
    }
}

fn editor(doc: Doc, wrap: bool) -> Editor {
    let options = EditorOptions {
        line_wrapping: wrap,
        ..EditorOptions::default()
    };
    let mut cm = Editor::new(&doc_text(doc), Spec::Null, options, Metrics::oracle());
    cm.set_size(600.0, 300.0);
    cm
}

fn cursor(cm: &mut Editor, line: i64, ch: i64) {
    cm.doc.set_cursor(Pos::new(line, ch), None);
}

fn sel(cm: &Editor) -> Vec<Sel> {
    cm.doc
        .list_selections()
        .iter()
        .map(|r| (r.anchor.line, r.anchor.ch, r.head.line, r.head.ch))
        .collect()
}

