fn check(ids: &[&str]) {
    let rows: Vec<&Row> = ROWS.iter().filter(|r| ids.contains(&r.0)).collect();
    assert!(!rows.is_empty(), "{ids:?}");
    let mut bad = Vec::new();
    for &&(id, doc, wrap, ml, mt, fl, ft, s, len, ud) in &rows {
        let mut cm = editor(doc, wrap);
        let got_mid = run(id, doc, &mut cm);
        let h = cm.doc.history_size();
        let got = (
            got_mid,
            (cm.display.scroll_left, cm.display.scroll_top),
            sel(&cm),
            cm.get_value().encode_utf16().count(),
            (h.undo, h.redo),
        );
        let want = ((ml, mt), (fl, ft), vec![s], len, ud);
        if got != want {
            bad.push(format!(
                "{id} {doc:?} wrap {wrap}: got {got:?} want {want:?}"
            ));
        }
    }
    assert!(
        bad.is_empty(),
        "{} of {} rows differ:\n{}",
        bad.len(),
        rows.len(),
        bad.join("\n")
    );
}

fn ids(prefix: &str) -> Vec<&'static str> {
    ROWS.iter()
        .map(|r| r.0)
        .filter(|i| i.starts_with(prefix))
        .collect()
}

