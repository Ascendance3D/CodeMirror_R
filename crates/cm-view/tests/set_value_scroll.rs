//! `setValue` scroll reset. `Doc.setValue` (src/model/Doc.js:74-80) replaces the text
//! with `makeChange`, then, when the document is attached to an editor, calls
//! `scrollToCoords(cm, 0, 0)` (src/display/scrolling.js:125-129) before it sets the
//! selection to the start with `sel_dontScroll`. `scrollToCoords` resolves a queued
//! `op.scrollToPos` from its estimate, then stores `op.scrollLeft = 0` and
//! `op.scrollTop = 0`, which `endOperation_finish` applies when the operation ends
//! (src/display/operations.js:144-152). A later scroll request in the same operation
//! replaces the reset; an earlier one is replaced by it. A detached document, and a
//! linked document without an editor, are left alone.
//!
//! The expected values are CM5 5.65.21 in headless Chromium 151 at
//! [`Metrics::oracle`] (DejaVu Sans Mono 32px, line-height 38px), `setSize(600, 300)`
