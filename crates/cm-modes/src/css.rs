//! Port of `mode/css/css.js` (CodeMirror 5.65.21): the `css` mode and the
//! `text/css`, `text/x-scss`, `text/x-less` and `text/x-gss` configurations,
//! quirks included.
//!
//! * The JS keeps `type` and `override` as variables of the mode closure, shared by
//!   every state of one mode instance and kept between tokens. They live in `Cell`s
//!   here. When `tokenBase`'s `-` branch matches nothing, it returns `undefined`
//!   without setting `type`, so the *previous* token's type drives the state machine,
//!   and `override += " error"` can then yield `"undefined error"`.
//! * The keyword tables are `css_tables.rs`, generated from the JS arrays.
//! * A MIME spec carries its tables and token hooks as a [`CssConfig`] under the
//!   option key `propertyKeywords` (the key the JS tests to decide whether to fall
//!   back to `text/css`). Plain options (`allowNested`, `lineComment`,
//!   `supportsAtComponent`, `inline`) are ordinary spec options, so user specs
//!   override them the way `createObj(found, spec)` does.
//! * JS regexps are hand-coded over UTF-16 code units; `\w`, `\d` and `/i` are
//!   ASCII-only as in non-unicode JS regexps.
//!
//! Gaps: keyword tables and `tokenHooks` are read only from a [`CssConfig`]. A spec
//! with plain-object tables (`propertyKeywords: {...}`, `valueKeywords`, ...) falls
//! back to `text/css`, and separate table keys are ignored. The
//! `registerHelper("hintWords", "css", allWords)` call is not ported.

