/// Which `tokenHooks` object a configuration has.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Hooks {
    /// `text/css` and `text/x-gss`: `"/"` only.
    Css,
    /// `text/x-scss`: `"/"`, `":"`, `"$"`, `"#"`.
    Scss,
    /// `text/x-less`: `"/"`, `"@"`, `"&"`.
    Less,
    /// No `tokenHooks` (a spec without hooks would crash the JS on `tokenHooks[ch]`;
    /// only reachable from Rust callers building their own config).
    None,
}

/// The table-valued part of a css parser config. `None` = property absent (`|| {}`).
#[derive(Clone, Debug)]
pub struct CssConfig {
    pub document_types: Option<&'static [&'static str]>,
    pub media_types: Option<&'static [&'static str]>,
    pub media_features: Option<&'static [&'static str]>,
    pub media_value_keywords: Option<&'static [&'static str]>,
    pub property_keywords: Option<&'static [&'static str]>,
    pub non_standard_property_keywords: Option<&'static [&'static str]>,
    pub font_properties: Option<&'static [&'static str]>,
    pub counter_descriptors: Option<&'static [&'static str]>,
    pub color_keywords: Option<&'static [&'static str]>,
    pub value_keywords: Option<&'static [&'static str]>,
    pub token_hooks: Hooks,
}

/// `set.hasOwnProperty(key)` for a generated (ASCII, sorted) table.
fn has(set: Option<&'static [&'static str]>, key: &[u16]) -> bool {
    let Some(set) = set else { return false };
    if key.iter().any(|&c| c >= 0x80) {
        return false;
    }
    let k: String = key.iter().map(|&c| c as u8 as char).collect();
    set.binary_search(&k.as_str()).is_ok()
}

/// Parser states (`states.*`); also the context types.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum St {
    Top,
    Block,
    Maybeprop,
    Prop,
    PropBlock,
    Parens,
    Pseudo,
    DocumentTypes,
    AtBlock,
    AtComponentBlock,
    AtBlockParens,
    RestrictedAtBlockBefore,
    RestrictedAtBlock,
    Keyframes,
    At,
    Interpolation,
}

/// css.js: `Context(type, indent, prev)`. Immutable once made, so `Rc` sharing equals
/// the JS shallow copy.
#[derive(Debug)]
pub struct Context {
    pub ty: St,
    /// A number, or Pass for a root context started from a Pass base ([`JsNum`]).
    pub indent: JsNum,
    pub prev: Option<Rc<Context>>,
}

/// The tokenizer in `state.tokenize` (`null` = `tokenBase`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Tokenize {
    Base,
    /// `tokenString(quote)`.
    String(u16),
    Parenthesized,
    CComment,
}

#[derive(Clone, Debug)]
pub struct CssState {
    pub tokenize: Tokenize,
    pub state: St,
    /// `stateArg`: the at-rule text (`null` = `None`).
    pub state_arg: Option<Vec<u16>>,
    /// Always set in practice; `None` only after `popAndPass` ran off the top, where
    /// the JS throws a TypeError immediately (here: a panic).
    pub context: Option<Rc<Context>>,
}

impl CssState {
    fn cx(&self) -> &Rc<Context> {
        self.context
            .as_ref()
            .expect("css.js: TypeError, state.context is null")
    }
}

/// A tokenizer result: a style string/null/undefined, `[style, type]`, or `false`
/// (a hook declining).
enum Res {
    Style(JsStr),
    Pair(JsStr, JsStr),
    False,
}

pub struct CssMode {
    inline: bool,
    indent_unit: f64,
    cfg: CssConfig,
    allow_nested: bool,
    line_comment: Option<String>,
    supports_at_component: bool,
    highlight_non_standard: bool,
    /// css.js: the closure variable `type`.
    ty: RefCell<JsStr>,
    /// css.js: the closure variable `override`.
    over: RefCell<JsStr>,
}

const fn u(c: char) -> u16 {
    c as u16
}

/// `/[\w\\\-]/`
fn w_bs_dash(c: u16) -> bool {
    is_js_word(c) || c == u('\\') || c == u('-')
}

/// `/[\w.%]/`
fn w_dot_pct(c: u16) -> bool {
    is_js_word(c) || c == u('.') || c == u('%')
}

fn m(len: usize) -> Option<RegexMatch> {
    Some(RegexMatch { index: 0, len })
}

fn sp(s: &[u16]) -> usize {
    s.iter().take_while(|&&c| is_js_space(c)).count()
}

/// `/^\s*:/`
fn re_space_colon(s: &[u16]) -> Option<RegexMatch> {
    let i = sp(s);
    (s.get(i) == Some(&u(':'))).then(|| RegexMatch {
        index: 0,
        len: i + 1,
    })
}

/// `/^\s*\w*/`
fn re_space_word(s: &[u16]) -> Option<RegexMatch> {
    let i = sp(s);
    m(i + s[i..].iter().take_while(|&&c| is_js_word(c)).count())
}

/// `/^-[\w\\\-]*/`
fn re_dash_ident(s: &[u16]) -> Option<RegexMatch> {
    if s.first() != Some(&u('-')) {
        return None;
    }
    m(1 + s[1..].iter().take_while(|&&c| w_bs_dash(c)).count())
}

/// `/^\w+-/` (the run can not contain `-`, so no backtracking helps).
fn re_word_dash(s: &[u16]) -> Option<RegexMatch> {
    let n = s.iter().take_while(|&&c| is_js_word(c)).count();
    (n > 0 && s.get(n) == Some(&u('-'))).then(|| RegexMatch {
        index: 0,
        len: n + 1,
    })
}

fn is_alpha_ci(c: u16) -> bool {
    (u('a')..=u('z')).contains(&c) || (u('A')..=u('Z')).contains(&c)
}

/// `/^-?[_a-z][_a-z0-9-]*/i`
fn re_qualifier(s: &[u16]) -> Option<RegexMatch> {
    let mut i = usize::from(s.first() == Some(&u('-')));
    let c = *s.get(i)?;
    if !(c == u('_') || is_alpha_ci(c)) {
        return None;
    }
    i += 1;
    i += s[i..]
        .iter()
        .take_while(|&&c| c == u('_') || c == u('-') || is_alpha_ci(c) || is_digit(c))
        .count();
    m(i)
}

/// `/^[\w-.]+(?=\()/` — the class is `\w`, `-`, `.`.
fn re_callee(s: &[u16]) -> Option<RegexMatch> {
    let n = s
        .iter()
        .take_while(|&&c| is_js_word(c) || c == u('-') || c == u('.'))
        .count();
    (n > 0 && s.get(n) == Some(&u('('))).then_some(RegexMatch { index: 0, len: n })
}

/// `/^\s*[\"\')]/`
fn re_paren_start(s: &[u16]) -> Option<RegexMatch> {
    let i = sp(s);
    matches!(s.get(i), Some(&c) if c == u('"') || c == u('\'') || c == u(')')).then(|| RegexMatch {
        index: 0,
        len: i + 1,
    })
}

/// `/^\s*:(?:\s|$)/`
fn re_colon_space(s: &[u16]) -> Option<RegexMatch> {
    let i = sp(s);
    if s.get(i) != Some(&u(':')) {
        return None;
    }
    match s.get(i + 1) {
        None => m(i + 1),
        Some(&c) if is_js_space(c) => m(i + 2),
        _ => None,
    }
}

/// `/^\s*\{/`
fn re_space_brace(s: &[u16]) -> Option<RegexMatch> {
    let i = sp(s);
    (s.get(i) == Some(&u('{'))).then(|| RegexMatch {
        index: 0,
        len: i + 1,
    })
}

/// `/^[\w-]+/`
fn re_word_dash_run(s: &[u16]) -> Option<RegexMatch> {
    let n = s
        .iter()
        .take_while(|&&c| is_js_word(c) || c == u('-'))
        .count();
    (n > 0).then_some(RegexMatch { index: 0, len: n })
}

/// ASCII case-insensitive `s.startsWith(lit)` (`/i` in a non-unicode regexp).
fn starts_ci(s: &[u16], lit: &str) -> bool {
    lit.len() <= s.len()
        && lit
            .bytes()
            .zip(s)
            .all(|(b, &c)| c < 0x80 && (c as u8).eq_ignore_ascii_case(&b))
}

/// ASCII case-insensitive equality.
fn eq_ci(s: &[u16], lit: &str) -> bool {
    s.len() == lit.len() && starts_ci(s, lit)
}

/// `/^(charset|document|font-face|import|(-(moz|ms|o|webkit)-)?keyframes|media|namespace|page|supports)\b/i`.
/// No alternative is a prefix of another, so the first that fits is the only one.
fn re_less_at_keyword(s: &[u16]) -> Option<RegexMatch> {
    let mut len = None;
    for w in [
        "charset",
        "document",
        "font-face",
        "import",
        "media",
        "namespace",
        "page",
        "supports",
        "keyframes",
    ] {
        if starts_ci(s, w) {
            len = Some(w.len());
        }
    }
    if len.is_none() {
        for p in ["-moz-", "-ms-", "-o-", "-webkit-"] {
            if starts_ci(s, p) && starts_ci(&s[p.len()..], "keyframes") {
                len = Some(p.len() + 9);
            }
        }
    }
    let n = len?;
    // `\b`: the matched text ends in a word character.
    (!s.get(n).is_some_and(|&c| is_js_word(c))).then_some(RegexMatch { index: 0, len: n })
}

/// `/^#([0-9a-fA-F]{3,4}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/.test(s)`
fn is_hex_color(s: &[u16]) -> bool {
    s.first() == Some(&u('#'))
        && matches!(s.len() - 1, 3 | 4 | 6 | 8)
        && s[1..].iter().all(|&c| is_hex(c))
}

impl CssMode {
    /// css.js: `ret(style, tp)`.
    fn ret(&self, style: Option<&str>, tp: Option<&str>) -> Res {
        *self.ty.borrow_mut() = tp.map_or(JsStr::Null, JsStr::s);
        Res::Style(style.map_or(JsStr::Null, JsStr::s))
    }

    fn set_override(&self, v: &str) {
        *self.over.borrow_mut() = JsStr::s(v);
    }

    fn override_error(&self) {
        let o = self.over.borrow().concat(" error");
        *self.over.borrow_mut() = o;
    }

    /// The `tokenHooks[ch]` functions of the four MIME configs.
    fn hook(&self, ch: u16, stream: &mut StringStream<'_>, state: &mut CssState) -> Option<Res> {
        let pair = |a: Option<&str>, b: Option<&str>| {
            Res::Pair(
                a.map_or(JsStr::Null, JsStr::s),
                b.map_or(JsStr::Null, JsStr::s),
            )
        };
        match (self.cfg.token_hooks, ch) {
            (Hooks::Css, c) if c == u('/') => {
                if stream.eat(u('*')).is_none() {
                    return Some(Res::False);
                }
                state.tokenize = Tokenize::CComment;
                Some(token_c_comment(stream, state))
            }
            (Hooks::Scss | Hooks::Less, c) if c == u('/') => {
                Some(if stream.eat(u('/')).is_some() {
                    stream.skip_to_end();
                    pair(Some("comment"), Some("comment"))
                } else if stream.eat(u('*')).is_some() {
                    state.tokenize = Tokenize::CComment;
                    token_c_comment(stream, state)
                } else {
                    pair(Some("operator"), Some("operator"))
                })
            }
            (Hooks::Scss, c) if c == u(':') => {
                Some(if stream.match_with(re_space_brace, false).is_some() {
                    pair(None, None)
                } else {
                    Res::False
                })
            }
            (Hooks::Scss, c) if c == u('$') => {
                stream.match_with(re_word_dash_run, true);
                Some(if stream.match_with(re_space_colon, false).is_some() {
                    pair(Some("variable-2"), Some("variable-definition"))
                } else {
                    pair(Some("variable-2"), Some("variable"))
                })
            }
            (Hooks::Scss, c) if c == u('#') => {
                if stream.eat(u('{')).is_none() {
                    return Some(Res::False);
                }
                Some(pair(None, Some("interpolation")))
            }
            (Hooks::Less, c) if c == u('@') => {
                if stream.eat(u('{')).is_some() {
                    return Some(pair(None, Some("interpolation")));
                }
                if stream.match_with(re_less_at_keyword, false).is_some() {
                    return Some(Res::False);
                }
                stream.eat_while(w_bs_dash);
                Some(if stream.match_with(re_space_colon, false).is_some() {
                    pair(Some("variable-2"), Some("variable-definition"))
                } else {
                    pair(Some("variable-2"), Some("variable"))
                })
            }
            (Hooks::Less, c) if c == u('&') => Some(pair(Some("atom"), Some("atom"))),
            _ => None,
        }
    }

    /// css.js: `tokenBase`.
    fn token_base(&self, stream: &mut StringStream<'_>, state: &mut CssState) -> Res {
        let ch = stream.next().expect("tokenBase at end of line");
        if let Some(result) = self.hook(ch, stream, state)
            && !matches!(result, Res::False) {
                return result;
            }
        if ch == u('@') {
            stream.eat_while(w_bs_dash);
            let cur = String::from_utf16_lossy(stream.current());
            self.ret(Some("def"), Some(&cur))
        } else if ch == u('=') || (ch == u('~') || ch == u('|')) && stream.eat(u('=')).is_some() {
            self.ret(None, Some("compare"))
        } else if ch == u('"') || ch == u('\'') {
            state.tokenize = Tokenize::String(ch);
            token_string(self, ch, stream, state)
        } else if ch == u('#') {
            stream.eat_while(w_bs_dash);
            self.ret(Some("atom"), Some("hash"))
        } else if ch == u('!') {
            stream.match_with(re_space_word, true);
            self.ret(Some("keyword"), Some("important"))
        } else if is_digit(ch) || ch == u('.') && stream.eat_fn(is_digit).is_some() {
            stream.eat_while(w_dot_pct);
            self.ret(Some("number"), Some("unit"))
        } else if ch == u('-') {
            // `/[\d.]/.test(stream.peek())`: undefined tests as "undefined".
            if stream.peek().is_some_and(|c| is_digit(c) || c == u('.')) {
                stream.eat_while(w_dot_pct);
                self.ret(Some("number"), Some("unit"))
            } else if stream.match_with(re_dash_ident, true).is_some() {
                stream.eat_while(w_bs_dash);
                if stream.match_with(re_space_colon, false).is_some() {
                    return self.ret(Some("variable-2"), Some("variable-definition"));
                }
                self.ret(Some("variable-2"), Some("variable"))
            } else if stream.match_with(re_word_dash, true).is_some() {
                self.ret(Some("meta"), Some("meta"))
            } else {
                // Falls off the end: `undefined`, and `type` keeps its old value.
                Res::Style(JsStr::Undefined)
            }
        } else if [u(','), u('+'), u('>'), u('*'), u('/')].contains(&ch) {
            self.ret(None, Some("select-op"))
        } else if ch == u('.') && stream.match_with(re_qualifier, true).is_some() {
            self.ret(Some("qualifier"), Some("qualifier"))
        } else if [
            u(':'),
            u(';'),
            u('{'),
            u('}'),
            u('['),
            u(']'),
            u('('),
            u(')'),
        ]
        .contains(&ch)
        {
            let t = String::from_utf16_lossy(&[ch]);
            self.ret(None, Some(&t))
        } else if stream.match_with(re_callee, true).is_some() {
            // `/^(url(-prefix)?|domain|regexp)$/i.test(stream.current())`
            let cur = stream.current();
            if eq_ci(cur, "url")
                || eq_ci(cur, "url-prefix")
                || eq_ci(cur, "domain")
                || eq_ci(cur, "regexp")
            {
                state.tokenize = Tokenize::Parenthesized;
            }
            self.ret(Some("variable callee"), Some("variable"))
        } else if w_bs_dash(ch) {
            stream.eat_while(w_bs_dash);
            self.ret(Some("property"), Some("word"))
        } else {
            self.ret(None, None)
        }
    }

    // Context management

    /// css.js: `pushContext(state, stream, type, indent)`; `indent_false` is
    /// `indent === false`.
    fn push_context(
        &self,
        state: &mut CssState,
        stream: &StringStream<'_>,
        ty: St,
        indent_false: bool,
    ) -> St {
        let indent =
            stream.indentation() as f64 + if indent_false { 0.0 } else { self.indent_unit };
        state.context = Some(Rc::new(Context {
            ty,
            indent: JsNum::Num(indent),
            prev: state.context.clone(),
        }));
        ty
    }

    /// css.js: `popContext(state)`.
    fn pop_context(&self, state: &mut CssState) -> St {
        let prev = state.cx().prev.clone();
        if prev.is_some() {
            state.context = prev;
        }
        state.cx().ty
    }

    /// css.js: `pass(type, stream, state)`.
    fn pass(&self, ty: &JsStr, stream: &mut StringStream<'_>, state: &mut CssState) -> St {
        let s = state.cx().ty;
        self.run_state(s, ty, stream, state)
    }

    /// css.js: `popAndPass(type, stream, state, n)`.
    fn pop_and_pass(
        &self,
        ty: &JsStr,
        stream: &mut StringStream<'_>,
        state: &mut CssState,
        n: usize,
    ) -> St {
        for _ in 0..n {
            state.context = state.cx().prev.clone();
        }
        self.pass(ty, stream, state)
    }

    /// css.js: `wordAsValue(stream)`.
    fn word_as_value(&self, stream: &StringStream<'_>) {
        let word = to_lower(stream.current());
        if has(self.cfg.value_keywords, &word) {
            self.set_override("atom");
        } else if has(self.cfg.color_keywords, &word) {
            self.set_override("keyword");
        } else {
            self.set_override("variable");
        }
    }

    fn run_state(
        &self,
        s: St,
        ty: &JsStr,
        stream: &mut StringStream<'_>,
        state: &mut CssState,
    ) -> St {
        match s {
            St::Top => self.st_top(ty, stream, state),
            St::Block => self.st_block(ty, stream, state),
            St::Maybeprop => {
                if ty.is(":") {
                    return self.push_context(state, stream, St::Prop, false);
                }
                self.pass(ty, stream, state)
            }
            St::Prop => self.st_prop(ty, stream, state),
            St::PropBlock => {
                if ty.is("}") {
                    return self.pop_context(state);
                }
                if ty.is("word") {
                    self.set_override("property");
                    return St::Maybeprop;
                }
                state.cx().ty
            }
            St::Parens => {
                if ty.is("{") || ty.is("}") {
                    return self.pop_and_pass(ty, stream, state, 1);
                }
                if ty.is(")") {
                    return self.pop_context(state);
                }
                if ty.is("(") {
                    return self.push_context(state, stream, St::Parens, false);
                }
                if ty.is("interpolation") {
                    return self.push_context(state, stream, St::Interpolation, false);
                }
                if ty.is("word") {
                    self.word_as_value(stream);
                }
                St::Parens
            }
            St::Pseudo => {
                if ty.is("meta") {
                    return St::Pseudo;
                }
                if ty.is("word") {
                    self.set_override("variable-3");
                    return state.cx().ty;
                }
                self.pass(ty, stream, state)
            }
            St::DocumentTypes => {
                if ty.is("word") && has(self.cfg.document_types, stream.current()) {
                    self.set_override("tag");
                    state.cx().ty
                } else {
                    self.st_at_block(ty, stream, state)
                }
            }
            St::AtBlock => self.st_at_block(ty, stream, state),
            St::AtComponentBlock => {
                if ty.is("}") {
                    return self.pop_and_pass(ty, stream, state, 1);
                }
                if ty.is("{") {
                    // `popContext(state) && pushContext(...)`: a type name is truthy.
                    self.pop_context(state);
                    let t = if self.allow_nested {
                        St::Block
                    } else {
                        St::Top
                    };
                    return self.push_context(state, stream, t, true);
                }
                if ty.is("word") {
                    self.set_override("error");
                }
                state.cx().ty
            }
            St::AtBlockParens => {
                if ty.is(")") {
                    return self.pop_context(state);
                }
                if ty.is("{") || ty.is("}") {
                    return self.pop_and_pass(ty, stream, state, 2);
                }
                self.st_at_block(ty, stream, state)
            }
            St::RestrictedAtBlockBefore => {
                if ty.is("{") {
                    return self.push_context(state, stream, St::RestrictedAtBlock, false);
                }
                if ty.is("word")
                    && state
                        .state_arg
                        .as_deref()
                        .is_some_and(|a| crate::js::eq(a, "@counter-style"))
                {
                    self.set_override("variable");
                    return St::RestrictedAtBlockBefore;
                }
                self.pass(ty, stream, state)
            }
            St::RestrictedAtBlock => {
                if ty.is("}") {
                    state.state_arg = None;
                    return self.pop_context(state);
                }
                if ty.is("word") {
                    let arg = state.state_arg.as_deref();
                    let word = to_lower(stream.current());
                    if (arg.is_some_and(|a| crate::js::eq(a, "@font-face"))
                        && !has(self.cfg.font_properties, &word))
                        || (arg.is_some_and(|a| crate::js::eq(a, "@counter-style"))
                            && !has(self.cfg.counter_descriptors, &word))
                    {
                        self.set_override("error");
                    } else {
                        self.set_override("property");
                    }
                    return St::Maybeprop;
                }
                St::RestrictedAtBlock
            }
            St::Keyframes => {
                if ty.is("word") {
                    self.set_override("variable");
                    return St::Keyframes;
                }
                if ty.is("{") {
                    return self.push_context(state, stream, St::Top, false);
                }
                self.pass(ty, stream, state)
            }
            St::At => {
                if ty.is(";") {
                    return self.pop_context(state);
                }
                if ty.is("{") || ty.is("}") {
                    return self.pop_and_pass(ty, stream, state, 1);
                }
                if ty.is("word") {
                    self.set_override("tag");
                } else if ty.is("hash") {
                    self.set_override("builtin");
                }
                St::At
            }
            St::Interpolation => {
                if ty.is("}") {
                    return self.pop_context(state);
                }
                if ty.is("{") || ty.is(";") {
                    return self.pop_and_pass(ty, stream, state, 1);
                }
                if ty.is("word") {
                    self.set_override("variable");
                } else if !ty.is("variable") && !ty.is("(") && !ty.is(")") {
                    self.set_override("error");
                }
                St::Interpolation
            }
        }
    }

    /// css.js: `states.top`.
    fn st_top(&self, ty: &JsStr, stream: &mut StringStream<'_>, state: &mut CssState) -> St {
        let t: Vec<u16> = ty.as_js_string().encode_utf16().collect();
        if ty.is("{") {
            return self.push_context(state, stream, St::Block, false);
        } else if ty.is("}") && state.cx().prev.is_some() {
            return self.pop_context(state);
        // `/@component/i.test(type)`: anywhere in String(type).
        } else if self.supports_at_component
            && (0..t.len()).any(|i| starts_ci(&t[i..], "@component"))
        {
            return self.push_context(state, stream, St::AtComponentBlock, false);
        // `/^@(-moz-)?document$/i`
        } else if eq_ci(&t, "@document") || eq_ci(&t, "@-moz-document") {
            return self.push_context(state, stream, St::DocumentTypes, false);
        // `/^@(media|supports|(-moz-)?document|import)$/i`
        } else if [
            "@media",
            "@supports",
            "@document",
            "@-moz-document",
            "@import",
        ]
        .iter()
        .any(|w| eq_ci(&t, w))
        {
            return self.push_context(state, stream, St::AtBlock, false);
        // `/^@(font-face|counter-style)/i` (a prefix test)
        } else if starts_ci(&t, "@font-face") || starts_ci(&t, "@counter-style") {
            state.state_arg = ty.as_deref().map(|s| s.encode_utf16().collect());
            return St::RestrictedAtBlockBefore;
        // `/^@(-(moz|ms|o|webkit)-)?keyframes$/i`
        } else if [
            "@keyframes",
            "@-moz-keyframes",
            "@-ms-keyframes",
            "@-o-keyframes",
            "@-webkit-keyframes",
        ]
        .iter()
        .any(|w| eq_ci(&t, w))
        {
            return St::Keyframes;
        } else if ty.as_deref().is_some_and(|s| s.starts_with('@')) {
            return self.push_context(state, stream, St::At, false);
        } else if ty.is("hash") {
            self.set_override("builtin");
        } else if ty.is("word") {
            self.set_override("tag");
        } else if ty.is("variable-definition") {
            return St::Maybeprop;
        } else if ty.is("interpolation") {
            return self.push_context(state, stream, St::Interpolation, false);
        } else if ty.is(":") {
            return St::Pseudo;
        } else if self.allow_nested && ty.is("(") {
            return self.push_context(state, stream, St::Parens, false);
        }
        state.cx().ty
    }

    /// css.js: `states.block`.
    fn st_block(&self, ty: &JsStr, stream: &mut StringStream<'_>, state: &mut CssState) -> St {
        if ty.is("word") {
            let word = to_lower(stream.current());
            if has(self.cfg.property_keywords, &word) {
                self.set_override("property");
                St::Maybeprop
            } else if has(self.cfg.non_standard_property_keywords, &word) {
                self.set_override(if self.highlight_non_standard {
                    "string-2"
                } else {
                    "property"
                });
                St::Maybeprop
            } else if self.allow_nested {
                self.set_override(if stream.match_with(re_colon_space, false).is_some() {
                    "property"
                } else {
                    "tag"
                });
                St::Block
            } else {
                self.override_error();
                St::Maybeprop
            }
        } else if ty.is("meta") {
            St::Block
        } else if !self.allow_nested && (ty.is("hash") || ty.is("qualifier")) {
            self.set_override("error");
            St::Block
        } else {
            self.st_top(ty, stream, state)
        }
    }

    /// css.js: `states.prop`.
    fn st_prop(&self, ty: &JsStr, stream: &mut StringStream<'_>, state: &mut CssState) -> St {
        if ty.is(";") {
            return self.pop_context(state);
        }
        if ty.is("{") && self.allow_nested {
            return self.push_context(state, stream, St::PropBlock, false);
        }
        if ty.is("}") || ty.is("{") {
            return self.pop_and_pass(ty, stream, state, 1);
        }
        if ty.is("(") {
            return self.push_context(state, stream, St::Parens, false);
        }
        if ty.is("hash") && !is_hex_color(stream.current()) {
            self.override_error();
        } else if ty.is("word") {
            self.word_as_value(stream);
        } else if ty.is("interpolation") {
            return self.push_context(state, stream, St::Interpolation, false);
        }
        St::Prop
    }

    /// css.js: `states.atBlock`.
    fn st_at_block(&self, ty: &JsStr, stream: &mut StringStream<'_>, state: &mut CssState) -> St {
        if ty.is("(") {
            return self.push_context(state, stream, St::AtBlockParens, false);
        }
        if ty.is("}") || ty.is(";") {
            return self.pop_and_pass(ty, stream, state, 1);
        }
        if ty.is("{") {
            self.pop_context(state);
            let t = if self.allow_nested {
                St::Block
            } else {
                St::Top
            };
            return self.push_context(state, stream, t, false);
        }
        if ty.is("interpolation") {
            return self.push_context(state, stream, St::Interpolation, false);
        }
        if ty.is("word") {
            let word = to_lower(stream.current());
            let c = &self.cfg;
            let o = if ["only", "not", "and", "or"]
                .iter()
                .any(|w| crate::js::eq(&word, w))
            {
                "keyword"
            } else if has(c.media_types, &word) {
                "attribute"
            } else if has(c.media_features, &word) {
                "property"
            } else if has(c.media_value_keywords, &word) {
                "keyword"
            } else if has(c.property_keywords, &word) {
                "property"
            } else if has(c.non_standard_property_keywords, &word) {
                if self.highlight_non_standard {
                    "string-2"
                } else {
                    "property"
                }
            } else if has(c.value_keywords, &word) {
                "atom"
            } else if has(c.color_keywords, &word) {
                "keyword"
            } else {
                "error"
            };
            self.set_override(o);
        }
        state.cx().ty
    }
}

/// css.js: `tokenString(quote)`.
fn token_string(
    mode: &CssMode,
    quote: u16,
    stream: &mut StringStream<'_>,
    state: &mut CssState,
) -> Res {
    let mut escaped = false;
    let mut ch = None;
    while let Some(c) = stream.next() {
        ch = Some(c);
        if c == quote && !escaped {
            if quote == u(')') {
                stream.back_up(1);
            }
            break;
        }
        escaped = !escaped && c == u('\\');
        ch = None;
    }
    if ch == Some(quote) || !escaped && quote != u(')') {
        state.tokenize = Tokenize::Base;
    }
    mode.ret(Some("string"), Some("string"))
}

/// css.js: `tokenParenthesized`.
fn token_parenthesized(mode: &CssMode, stream: &mut StringStream<'_>, state: &mut CssState) -> Res {
    stream.next(); // Must be '('
    if stream.match_with(re_paren_start, false).is_none() {
        state.tokenize = Tokenize::String(u(')'));
    } else {
        state.tokenize = Tokenize::Base;
    }
    mode.ret(None, Some("("))
}

/// css.js: `tokenCComment` (returns `["comment", "comment"]`, not through `ret`).
fn token_c_comment(stream: &mut StringStream<'_>, state: &mut CssState) -> Res {
    let mut maybe_end = false;
    while let Some(ch) = stream.next() {
        if maybe_end && ch == u('/') {
            state.tokenize = Tokenize::Base;
            break;
        }
        maybe_end = ch == u('*');
    }
    Res::Pair(JsStr::s("comment"), JsStr::s("comment"))
}

impl Mode for CssMode {
    fn name(&self) -> &str {
        "css"
    }

    /// css.js: `startState(base)`.
    fn start_state(&self, base: JsArg, _a2: JsArg) -> Option<State> {
        let ty = if self.inline { St::Block } else { St::Top };
        Some(State::new(CssState {
            tokenize: Tokenize::Base,
            state: ty,
            state_arg: None,
            context: Some(Rc::new(Context {
                ty,
                indent: JsNum::or_zero(base),
                prev: None,
            })),
        }))
    }

    /// css.js: `token(stream, state)`.
    fn token(&self, stream: &mut StringStream<'_>, state: &mut State) -> Option<String> {
        let state = state.get_mut::<CssState>();
        if state.tokenize == Tokenize::Base && stream.eat_space() {
            return None;
        }
        let res = match state.tokenize {
            Tokenize::Base => self.token_base(stream, state),
            Tokenize::String(q) => token_string(self, q, stream, state),
            Tokenize::Parenthesized => token_parenthesized(self, stream, state),
            Tokenize::CComment => token_c_comment(stream, state),
        };
        let style = match res {
            Res::Style(s) => s,
            Res::Pair(s, t) => {
                *self.ty.borrow_mut() = t;
                s
            }
            Res::False => unreachable!("hooks resolve `false` in tokenBase"),
        };
        *self.over.borrow_mut() = style;
        let ty = self.ty.borrow().clone();
        if !ty.is("comment") {
            let s = state.state;
            state.state = self.run_state(s, &ty, stream, state);
        }
        self.over.borrow().clone().into_style()
    }

    /// css.js: `indent(state, textAfter)`.
    fn indent(&self, state: &State, text_after: &[u16], _line: &[u16]) -> Option<f64> {
        let state = state.get::<CssState>();
        let mut cx = state.cx().clone();
        let ch = text_after.first().copied();
        let mut indent = cx.indent;
        if cx.ty == St::Prop && (ch == Some(u('}')) || ch == Some(u(')'))) {
            cx = cx.prev.clone().expect("prop context has a parent");
        }
        if let Some(prev) = cx.prev.clone() {
            if ch == Some(u('}'))
                && matches!(
                    cx.ty,
                    St::Block | St::Top | St::Interpolation | St::RestrictedAtBlock
                )
            {
                // Resume indentation from parent context.
                cx = prev;
                indent = cx.indent;
            } else if ch == Some(u(')')) && matches!(cx.ty, St::Parens | St::AtBlockParens)
                || ch == Some(u('{')) && matches!(cx.ty, St::At | St::AtBlock)
            {
                // Dedent relative to current context: `Math.max(0, ...)` keeps NaN.
                let d = cx.indent.minus(self.indent_unit);
                indent = JsNum::Num(if d.is_nan() { f64::NAN } else { d.max(0.0) });
            }
        }
        indent.value()
    }

    fn has_indent(&self) -> bool {
        true
    }

    fn electric_chars(&self) -> Option<&str> {
        Some("}")
    }
    fn line_comment(&self) -> Option<&str> {
        self.line_comment.as_deref()
    }
    fn block_comment_start(&self) -> Option<&str> {
        Some("/*")
    }
    fn block_comment_end(&self) -> Option<&str> {
        Some("*/")
    }
    fn prop(&self, name: &str) -> Option<ConfigValue> {
        match name {
            "electricChars" => Some(ConfigValue::Str("}".into())),
            "blockCommentStart" => Some(ConfigValue::Str("/*".into())),
            "blockCommentEnd" => Some(ConfigValue::Str("*/".into())),
            "blockCommentContinue" => Some(ConfigValue::Str(" * ".into())),
            "lineComment" => self.line_comment.clone().map(ConfigValue::Str),
            "fold" => Some(ConfigValue::Str("brace".into())),
            _ => None,
        }
    }
}

/// The `defineMode("css", ...)` factory body.
fn make(registry: &Registry, config: &ModeOptions, parser_config: &ModeSpec) -> CssMode {
    let inline = parser_config.truthy("inline");
    let has_cfg = parser_config
        .get("propertyKeywords")
        .is_some_and(|v| v.truthy());
    let resolved;
    let pc = if has_cfg
        && parser_config
            .get("propertyKeywords")
            .and_then(|v| v.as_obj::<CssConfig>())
            .is_some()
    {
        parser_config
    } else {
        // `if (!parserConfig.propertyKeywords) parserConfig = CodeMirror.resolveMode("text/css")`
        resolved = registry.resolve_mode(&Spec::from("text/css"));
        &resolved
    };
    let cfg = pc
        .get("propertyKeywords")
        .and_then(|v| v.as_obj::<CssConfig>())
        .cloned()
        .unwrap_or(CssConfig {
            document_types: None,
            media_types: None,
            media_features: None,
            media_value_keywords: None,
            property_keywords: None,
            non_standard_property_keywords: None,
            font_properties: None,
            counter_descriptors: None,
            color_keywords: None,
            value_keywords: None,
            token_hooks: Hooks::None,
        });
    CssMode {
        inline,
        indent_unit: config.indent_unit as f64,
        cfg,
        allow_nested: pc.truthy("allowNested"),
        // `lineComment: lineComment` — only a string is useful to callers.
        line_comment: pc
            .get("lineComment")
            .and_then(|v| v.as_str())
            .map(str::to_string),
        // `parserConfig.supportsAtComponent === true`
        supports_at_component: pc.get("supportsAtComponent") == Some(&ConfigValue::Bool(true)),
        highlight_non_standard: config.highlight_non_standard_property_keywords != Some(false),
        ty: RefCell::new(JsStr::Undefined),
        over: RefCell::new(JsStr::Undefined),
    }
}

fn mime(cfg: CssConfig, helper_type: Option<&str>) -> ModeSpec {
    let mut s = ModeSpec::named("css").with("propertyKeywords", ConfigValue::Obj(Rc::new(cfg)));
    s.helper_type = helper_type.map(str::to_string);
    s
}

/// `defineMode("css")` and the four `defineMIME` calls.
pub fn register(r: &mut Registry) {
    // `CodeMirror.registerHelper("hintWords", "css", allWords)`
    let all_words: Vec<String> = CSS_HINT_WORDS.iter().map(|w| w.to_string()).collect();
    r.helpers.register("hintWords", "css", Rc::new(all_words));
    r.define_mode(
        "css",
        Rc::new(|reg, config, spec| Rc::new(make(reg, config, spec)) as Rc<dyn Mode>),
    );
    let all = CssConfig {
        document_types: Some(DOCUMENT_TYPES),
        media_types: Some(MEDIA_TYPES),
        media_features: Some(MEDIA_FEATURES),
        media_value_keywords: Some(MEDIA_VALUE_KEYWORDS),
        property_keywords: Some(PROPERTY_KEYWORDS),
        non_standard_property_keywords: Some(NON_STANDARD_PROPERTY_KEYWORDS),
        font_properties: Some(FONT_PROPERTIES),
        counter_descriptors: Some(COUNTER_DESCRIPTORS),
        color_keywords: Some(COLOR_KEYWORDS),
        value_keywords: Some(VALUE_KEYWORDS),
        token_hooks: Hooks::Css,
    };
    r.define_mime("text/css", MimeTarget::Spec(mime(all.clone(), None)));
    // scss / less: no documentTypes, no counterDescriptors.
    let nested = |hooks| CssConfig {
        document_types: None,
        counter_descriptors: None,
        token_hooks: hooks,
        ..all.clone()
    };
    r.define_mime(
        "text/x-scss",
        MimeTarget::Spec(
            mime(nested(Hooks::Scss), Some("scss"))
                .with("allowNested", ConfigValue::Bool(true))
                .with("lineComment", ConfigValue::Str("//".into())),
        ),
    );
    r.define_mime(
        "text/x-less",
        MimeTarget::Spec(
            mime(nested(Hooks::Less), Some("less"))
                .with("allowNested", ConfigValue::Bool(true))
                .with("lineComment", ConfigValue::Str("//".into())),
        ),
    );
    // gss: no mediaValueKeywords; supportsAtComponent.
    r.define_mime(
        "text/x-gss",
        MimeTarget::Spec(
            mime(
                CssConfig {
                    media_value_keywords: None,
                    ..all
                },
                Some("gss"),
            )
            .with("supportsAtComponent", ConfigValue::Bool(true)),
        ),
    );
}

