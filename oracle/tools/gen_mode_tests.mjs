/**
 * C4: turn the upstream mode test files (MT() style, test/mode_test.js) into Rust
 * tests. Each upstream file is evaluated with a stub `test.mode` that records the
 * test name, the getMode config/spec and the token lines; the real getMode (from
 * runmode.node.js) supplies `mode.name`, as test.mode's name prefix needs it.
 *
 *   node oracle/tools/gen_mode_tests.mjs > crates/cm-modes/tests/upstream_mode_tests.rs
 */
import { createRequire } from "node:module";
import { readFileSync } from "node:fs";
import { join, normalize } from "node:path";
import { fileURLToPath } from "node:url";

const HERE    = normalize (join (fileURLToPath (import.meta.url), "..", ".."));
const ROOT    = normalize (join (HERE, ".."));
const require = createRequire (import.meta.url);
const CM      = require (join (HERE, "cm5-build", "addon", "runmode", "runmode.node.js"));
require (join (HERE, "cm5-build", "addon", "mode", "simple.js"));
for (const m of ["xml/xml.js", "javascript/javascript.js", "css/css.js", "htmlmixed/htmlmixed.js", "rust/rust.js"])
   require (join (HERE, "cm5-build", "mode", m));

const FILES = ["mode/xml/test.js", "mode/javascript/test.js", "mode/css/test.js",
               "mode/css/gss_test.js", "mode/css/scss_test.js", "mode/css/less_test.js",
               "mode/rust/test.js"];

const tests = [];
for (const file of FILES)
{
   const src = readFileSync (join (ROOT, "upstream", "codemirror5", file), "utf8");
   const fakeCM = {
      getMode: (cfg, spec) => ({ __cfg: cfg, __spec: spec, name: CM .getMode (cfg, spec) .name }),
   };
   const test = { mode: (name, mode, tokens, modeName) =>
      tests .push ({ file, name: (modeName || mode .name) + "_" + name, cfg: mode .__cfg, spec: mode .__spec, tokens }) };
   new Function ("CodeMirror", "test", src) (fakeCM, test);
}

const rs = s => JSON .stringify (s);  // JSON string escapes are valid Rust escapes for these inputs
function specRs (spec)
{
   if (typeof spec == "string") return `Spec::from(${rs (spec)})`;
   let out = `ModeSpec::named(${rs (spec .name)})`;
   for (const [k, v] of Object .entries (spec))
   {
      if (k == "name") continue;
      if (typeof v != "boolean") throw new Error ("unsupported spec option " + k);
      out += `.with(${rs (k)}, ConfigValue::Bool(${v}))`;
   }
   return `Spec::Obj(${out})`;
}

const seen = new Map ();
let out = `//! Upstream CodeMirror 5 mode tests, ported. GENERATED by
//! \`node oracle/tools/gen_mode_tests.mjs\` from the files below; do not edit by hand.
//! Each test cites its upstream file and the name \`test.mode\` registers it under.
//! The harness is \`common::mode_test\`, a port of \`test/mode_test.js\` (token
//! merging, style sorting and the per-line indentation check included).
//!
//! ${FILES .map (f => "upstream/codemirror5/" + f) .join ("\n//! ")}

#![cfg_attr(rustfmt, rustfmt::skip)]

mod common;

#[allow(unused_imports)]
use cm_modes::{ConfigValue, ModeSpec, Registry, Spec};

fn mt(file: &str, name: &str, spec: Spec, indent_unit: i64, lines: &[&str]) {
    let r = Registry::with_all_modes();
    if let Err(e) = common::mode_test(&r, &spec, indent_unit, lines) {
        panic!("{file} {name}: {e}");
    }
}
`;
for (const t of tests)
{
   let fn = t .name .replace (/[^A-Za-z0-9_]/g, "_") .toLowerCase ();
   const n = (seen .get (fn) || 0) + 1;
   seen .set (fn, n);
   if (n > 1) fn += "_" + n;
   out += `
/// ${t .file}: \`${t .name}\`
#[test]
fn ${fn}() {
    mt(${rs (t .file)}, ${rs (t .name)}, ${specRs (t .spec)}, ${t .cfg .indentUnit}, &[
${t .tokens .map (l => "        " + rs (l) + ",") .join ("\n")}
    ]);
}
`;
}
process .stdout .write (out);
console .error (`${tests .length} upstream mode tests from ${FILES .length} files`);
