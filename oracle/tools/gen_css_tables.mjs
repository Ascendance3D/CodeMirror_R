/**
 * C4: generate crates/cm-modes/src/css_tables.rs from the keyword arrays in
 * upstream/codemirror5/mode/css/css.js (lines from `function keySet` to
 * `valueKeywords = keySet(...)`), evaluated as JS. keySet lowercases every key; the
 * Rust tables hold the lowercased keys, sorted (binary search), duplicates removed.
 *
 *   node oracle/tools/gen_css_tables.mjs > crates/cm-modes/src/css_tables.rs
 */
import { readFileSync } from "node:fs";
import { join, normalize } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = normalize (join (fileURLToPath (import.meta.url), "..", "..", ".."));
const src  = readFileSync (join (ROOT, "upstream/codemirror5/mode/css/css.js"), "utf8");
const a = src .indexOf ("  function keySet(array)"), b = src .indexOf ("valueKeywords = keySet(valueKeywords_);");
const body = src .slice (a, b) + "valueKeywords = keySet(valueKeywords_);\n";
const names = ["documentTypes", "mediaTypes", "mediaFeatures", "mediaValueKeywords", "propertyKeywords",
               "nonStandardPropertyKeywords", "fontProperties", "counterDescriptors", "colorKeywords", "valueKeywords"];
const sets = new Function (body + "return {" + names .join (",") + "};") ();
const up = s => s .replace (/[A-Z]/g, c => "_" + c) .toUpperCase ();
let out = `//! Keyword tables of \`mode/css/css.js\` (CodeMirror 5.65.21). GENERATED by
//! \`node oracle/tools/gen_css_tables.mjs\`; do not edit by hand. Keys are as \`keySet\`
//! stores them (lowercased), sorted by UTF-16 code units for binary search.
`;
for (const n of names)
{
   const keys = Object .keys (sets [n]) .sort ((x, y) => x < y ? -1 : x > y ? 1 : 0);
   out += `\n/// \`${n}\` (${keys .length} keys)\npub static ${up (n)}: &[&str] = &[\n`;
   for (let i = 0; i < keys .length; i += 6)
      out += "    " + keys .slice (i, i + 6) .map (k => JSON .stringify (k)) .join (", ") + ",\n";
   out += "];\n";
}
process .stdout .write (out);
